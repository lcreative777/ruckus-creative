// scripts/fetch-unsplash.mjs
//
// One-shot: pull a curated set of surf / ocean / mountain photographs from
// Unsplash for the inner-page headers, download them into src/assets/backgrounds/
// and write an attribution manifest.
//
// Deliberately build-time, not runtime:
//   - the API key never reaches the Worker or the browser
//   - Astro re-encodes each image to AVIF/WebP with responsive widths
//   - no per-request API call, so no rate limit and no added latency
//
// Unsplash API Guidelines compliance (https://help.unsplash.com/en/articles/2511245):
//   - photographer name + profile link and an "Unsplash" link are stored in the
//     manifest so the site can attribute every image it displays
//   - both links carry the required utm_source / utm_medium parameters
//   - the per-photo download endpoint is triggered once here, which is what
//     Unsplash asks for when an app makes use of a photo
//
// Usage: node scripts/fetch-unsplash.mjs [--per-query 4]
// Reads the Access Key from ./unsplash.txt (gitignored) or UNSPLASH_ACCESS_KEY.
import { mkdir, writeFile, readFile } from 'node:fs/promises';
import { join } from 'node:path';

const QUERIES = ['surf', 'ocean', 'mountains'];
const APP_NAME = 'ruckus_creative';
const UTM = `utm_source=${APP_NAME}&utm_medium=referral`;

const args = process.argv.slice(2);
const flag = (name, fallback) => {
  const i = args.indexOf(name);
  return i === -1 ? fallback : args[i + 1];
};
const PER_QUERY = Number(flag('--per-query', '4'));

const ROOT = new URL('..', import.meta.url).pathname;
const DEST = join(ROOT, 'src/assets/backgrounds');
const MANIFEST = join(ROOT, 'src/data/backgrounds.json');

/** Access Key only — the Secret is for OAuth user auth, which this does not use. */
async function accessKey() {
  if (process.env.UNSPLASH_ACCESS_KEY) return process.env.UNSPLASH_ACCESS_KEY.trim();
  let text;
  try {
    text = await readFile(join(ROOT, 'unsplash.txt'), 'utf8');
  } catch {
    throw new Error('No UNSPLASH_ACCESS_KEY set and unsplash.txt not found.');
  }
  // The file is label-on-one-line, value-on-the-next.
  const lines = text.split('\n').map(l => l.trim()).filter(Boolean);
  const i = lines.findIndex(l => /^access key$/i.test(l));
  const key = i !== -1 ? lines[i + 1] : null;
  if (!key) throw new Error('Could not find an "Access Key" line in unsplash.txt.');
  return key;
}

const api = async (url, key) => {
  const res = await fetch(url, {
    headers: { Authorization: `Client-ID ${key}`, 'Accept-Version': 'v1' },
  });
  if (!res.ok) throw new Error(`${res.status} ${res.statusText} for ${url.split('?')[0]}`);
  return res.json();
};

const key = await accessKey();
await mkdir(DEST, { recursive: true });

const entries = [];

for (const query of QUERIES) {
  const url = `https://api.unsplash.com/search/photos?query=${encodeURIComponent(query)}`
    + `&per_page=${PER_QUERY}&orientation=landscape&content_filter=high`;
  const data = await api(url, key);

  for (const photo of data.results ?? []) {
    const file = `${query}-${photo.id}.jpg`;
    // A wide, quality-capped render — the header band is full-bleed and sits
    // under a 75% black overlay, so grain matters more than absolute fidelity.
    const src = `${photo.urls.raw}&w=2400&q=80&fm=jpg&fit=max`;
    const bin = await fetch(src);
    if (!bin.ok) { console.warn(`  ! ${bin.status} ${file}`); continue; }
    await writeFile(join(DEST, file), Buffer.from(await bin.arrayBuffer()));

    // Unsplash asks apps to hit this endpoint when they make use of a photo.
    try { await api(photo.links.download_location, key); } catch { /* non-fatal */ }

    entries.push({
      file,
      query,
      alt: photo.alt_description ?? `${query} photograph`,
      color: photo.color ?? '#121110',
      photographer: photo.user.name,
      photographerUrl: `${photo.user.links.html}?${UTM}`,
      photoUrl: `${photo.links.html}?${UTM}`,
    });
    console.log(`  ↓ ${file}  — ${photo.user.name}`);
  }
}

if (entries.length === 0) throw new Error('No images were downloaded; refusing to write an empty manifest.');

await writeFile(MANIFEST, JSON.stringify({
  note: 'Generated by scripts/fetch-unsplash.mjs. Attribution is required by the '
    + 'Unsplash API Guidelines — every rendered image must credit its photographer.',
  unsplashUrl: `https://unsplash.com/?${UTM}`,
  images: entries,
}, null, 2) + '\n', 'utf8');

console.log(`\n${entries.length} images in src/assets/backgrounds/, manifest at src/data/backgrounds.json`);
